    /// <summary>
    /// What each creature class is: its species, and whether that species is biological or
    /// mechanical. CreatureInfo used to carry an empty flag list, so nothing server-side knew
    /// what a creature was made of - which is the whole difference between Salvage and Tissue
    /// Extraction, one refusing biologicals and the other mechanicals.
    ///
    /// Reconstructed, like tool_type, because the originals were the 2009 server's and the
    /// client carries no per-creature table either. Two sources, and they agree.
    ///
    /// The species comes from the class name. The client's flag table has a SPECIES_* entry for
    /// forty-six families and the entity class names carry the family, so Bane_Thrax_Soldier_*
    /// is SPECIES_THRAX. 293 of the 421 classes with the Creature augmentation match one; the
    /// other 128 are ambient pets, vehicles, test and placeholder classes and named bosses, and
    /// are left with no flags rather than guessed at.
    ///
    /// Whether the species is biological or mechanical is then checked against the junk it
    /// drops. 149 Loot_Junk_&lt;family&gt;_&lt;part&gt; classes exist and the vocabulary is
